const DICT: Record<Lang, Dict> = { ar, fr, en };

interface I18nValue {
  lang: Lang;
  dir: 'rtl' | 'ltr';
  setLang: (lang: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  languages: typeof LANGS;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('naseej.lang') as Lang | null;
    return saved && DICT[saved] ? saved : 'ar';
  });

  useEffect(() => {
    // dir on <html> mirrors the whole layout: no per-component RTL logic needed.
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    localStorage.setItem('naseej.lang', lang);
  }, [lang]);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const raw = DICT[lang][key] ?? DICT.en[key] ?? key;
      if (!vars) return raw;
      return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
    },
    [lang],
  );

  return (
    <I18nContext.Provider
      value={{ lang, dir: lang === 'ar' ? 'rtl' : 'ltr', setLang: setLangState, t, languages: LANGS }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
